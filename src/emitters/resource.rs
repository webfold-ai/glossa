//! Universal Resource Catalog Emitter.
//!
//! Emits translated Apeiron catalogs into standardized i18n file formats:
//! JSON, YAML, GNU gettext PO, Mozilla Fluent, Android XML, Apple iOS Strings,
//! Flutter ARB, Java/Kotlin .properties, XLIFF 1.2, and CSV.

use std::collections::BTreeMap;

/// Emits translations as formatted JSON.
pub fn emit_json(catalog: &BTreeMap<String, String>) -> String {
    let mut map = serde_json::Map::new();
    for (k, v) in catalog {
        map.insert(k.clone(), serde_json::Value::String(v.clone()));
    }
    serde_json::to_string_pretty(&serde_json::Value::Object(map)).unwrap_or_else(|_| "{}".to_string())
}

/// Emits translations as standard YAML.
pub fn emit_yaml(catalog: &BTreeMap<String, String>, locale: &str) -> String {
    let mut out = String::new();
    out.push_str(&format!("{locale}:\n"));
    for (k, v) in catalog {
        let clean_v = v.replace('"', "\\\"").replace('\n', "\\n");
        if k.contains('.') {
            out.push_str(&format!("  \"{}\": \"{}\"\n", k, clean_v));
        } else {
            out.push_str(&format!("  {}: \"{}\"\n", k, clean_v));
        }
    }
    out
}

/// Emits translations as Android XML (`res/values-{locale}/strings.xml`).
pub fn emit_android_xml(catalog: &BTreeMap<String, String>) -> String {
    let mut out = String::new();
    out.push_str("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    out.push_str("<resources>\n");
    for (k, v) in catalog {
        let safe_name = sanitize_xml_identifier(k);
        let escaped_val = v
            .replace('&', "&amp;")
            .replace('<', "&lt;")
            .replace('>', "&gt;")
            .replace('\'', "\\'")
            .replace('"', "\\\"");
        out.push_str(&format!("    <string name=\"{safe_name}\">{escaped_val}</string>\n"));
    }
    out.push_str("</resources>\n");
    out
}

/// Emits translations as Apple iOS / macOS `.strings` file.
pub fn emit_ios_strings(catalog: &BTreeMap<String, String>) -> String {
    let mut out = String::new();
    out.push_str("/* Localized Strings Generated by Glossa */\n\n");
    for (k, v) in catalog {
        let escaped_k = k.replace('\\', "\\\\").replace('"', "\\\"");
        // Re-convert {var} or {name} back to %@ for iOS format strings
        let ios_val = convert_slots_to_ios(v);
        let escaped_v = ios_val.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n");
        out.push_str(&format!("\"{escaped_k}\" = \"{escaped_v}\";\n"));
    }
    out
}

/// Emits translations as Flutter ARB file (`intl_{locale}.arb`).
pub fn emit_flutter_arb(catalog: &BTreeMap<String, String>, locale: &str) -> String {
    let mut map = serde_json::Map::new();
    map.insert("@@locale".to_string(), serde_json::Value::String(locale.to_string()));
    for (k, v) in catalog {
        let safe_key = sanitize_camel_case(k);
        map.insert(safe_key, serde_json::Value::String(v.clone()));
    }
    serde_json::to_string_pretty(&serde_json::Value::Object(map)).unwrap_or_else(|_| "{}".to_string())
}

/// Emits translations as Java / Kotlin `.properties` file.
pub fn emit_properties(catalog: &BTreeMap<String, String>) -> String {
    let mut out = String::new();
    out.push_str("# Localized properties generated by Glossa\n");
    for (k, v) in catalog {
        let escaped_v = v.replace('\n', "\\n");
        out.push_str(&format!("{k} = {escaped_v}\n"));
    }
    out
}

/// Emits translations as standard XLIFF 1.2 XML file.
pub fn emit_xliff(catalog: &BTreeMap<String, String>, source_locale: &str, target_locale: &str) -> String {
    let mut out = String::new();
    out.push_str("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    out.push_str(&format!(
        "<xliff version=\"1.2\" xmlns=\"urn:oasis:names:tc:xliff:document:1.2\">\n  <file source-language=\"{}\" target-language=\"{}\" datatype=\"plaintext\">\n    <body>\n",
        source_locale, target_locale
    ));

    for (k, v) in catalog {
        let safe_id = sanitize_xml_identifier(k);
        let escaped_v = v
            .replace('&', "&amp;")
            .replace('<', "&lt;")
            .replace('>', "&gt;");
        out.push_str(&format!(
            "      <trans-unit id=\"{safe_id}\">\n        <source>{safe_id}</source>\n        <target>{escaped_v}</target>\n      </trans-unit>\n"
        ));
    }

    out.push_str("    </body>\n  </file>\n</xliff>\n");
    out
}

/// Emits translations as CSV file.
pub fn emit_csv(catalog: &BTreeMap<String, String>) -> String {
    let mut out = String::from("key,target\n");
    for (k, v) in catalog {
        let escaped_k = k.replace('"', "\"\"");
        let escaped_v = v.replace('"', "\"\"");
        out.push_str(&format!("\"{escaped_k}\",\"{escaped_v}\"\n"));
    }
    out
}

/// Emits translations as GNU gettext PO file.
pub fn emit_po(catalog: &BTreeMap<String, String>, locale: &str) -> String {
    let mut out = String::new();
    out.push_str("msgid \"\"\n");
    out.push_str("msgstr \"\"\n");
    out.push_str(&format!("\"Language: {locale}\\n\"\n"));
    out.push_str("\"MIME-Version: 1.0\\n\"\n");
    out.push_str("\"Content-Type: text/plain; charset=UTF-8\\n\"\n");
    out.push_str("\"Content-Transfer-Encoding: 8bit\\n\"\n\n");

    for (k, v) in catalog {
        let escaped_k = escape_po_string(k);
        let escaped_v = escape_po_string(v);
        out.push_str(&format!("msgid \"{escaped_k}\"\n"));
        out.push_str(&format!("msgstr \"{escaped_v}\"\n\n"));
    }

    out
}

/// Emits translations as Mozilla Fluent (.ftl) file.
pub fn emit_fluent(catalog: &BTreeMap<String, String>) -> String {
    let mut out = String::new();
    for (k, v) in catalog {
        let safe_key = k
            .chars()
            .map(|c| if c.is_alphanumeric() || c == '-' || c == '_' { c } else { '_' })
            .collect::<String>();
        let fluent_val = convert_slots_to_fluent(v);
        out.push_str(&format!("{safe_key} = {fluent_val}\n"));
    }
    out
}

fn escape_po_string(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n")
}

fn convert_slots_to_fluent(s: &str) -> String {
    let mut out = String::new();
    let chars: Vec<char> = s.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '{' && i + 1 < chars.len() && chars[i + 1] != '{' && chars[i + 1] != '$' {
            out.push('{');
            out.push('$');
            i += 1;
        } else {
            out.push(chars[i]);
            i += 1;
        }
    }
    out
}

fn convert_slots_to_ios(s: &str) -> String {
    // Replace `{...}` with `%@`
    let mut out = String::new();
    let chars: Vec<char> = s.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '{' {
            while i < chars.len() && chars[i] != '}' {
                i += 1;
            }
            if i < chars.len() {
                i += 1; // skip '}'
            }
            out.push_str("%@");
        } else {
            out.push(chars[i]);
            i += 1;
        }
    }
    out
}

fn sanitize_xml_identifier(s: &str) -> String {
    let mut res = String::new();
    for c in s.chars() {
        if c.is_alphanumeric() || c == '_' {
            res.push(c);
        } else {
            res.push('_');
        }
    }
    if res.is_empty() || res.chars().next().unwrap().is_numeric() {
        format!("msg_{res}")
    } else {
        res
    }
}

fn sanitize_camel_case(s: &str) -> String {
    let mut res = String::new();
    let mut cap_next = false;
    for c in s.chars() {
        if c.is_alphanumeric() {
            if cap_next {
                res.extend(c.to_uppercase());
                cap_next = false;
            } else {
                res.push(c);
            }
        } else {
            cap_next = true;
        }
    }
    if res.is_empty() { "msg".to_string() } else { res }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_emit_all_formats() {
        let mut map = BTreeMap::new();
        map.insert("hello".to_string(), "Hello, {name}!".to_string());
        map.insert("bye".to_string(), "Goodbye".to_string());

        let json = emit_json(&map);
        assert!(json.contains("\"hello\": \"Hello, {name}!\""));

        let yaml = emit_yaml(&map, "es");
        assert!(yaml.contains("es:\n"));
        assert!(yaml.contains("hello: \"Hello, {name}!\""));

        let xml = emit_android_xml(&map);
        assert!(xml.contains("<string name=\"hello\">Hello, {name}!</string>"));

        let ios = emit_ios_strings(&map);
        assert!(ios.contains("\"hello\" = \"Hello, %@!\";"));

        let arb = emit_flutter_arb(&map, "es");
        assert!(arb.contains("\"@@locale\": \"es\""));
        assert!(arb.contains("\"hello\": \"Hello, {name}!\""));

        let prop = emit_properties(&map);
        assert!(prop.contains("hello = Hello, {name}!"));

        let xlf = emit_xliff(&map, "en", "es");
        assert!(xlf.contains("<trans-unit id=\"hello\">"));
        assert!(xlf.contains("<target>Hello, {name}!</target>"));

        let csv = emit_csv(&map);
        assert!(csv.contains("\"hello\",\"Hello, {name}!\""));
    }
}
