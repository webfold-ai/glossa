//! Message accessor code generator (TypeScript & Rust).
//!
//! Compiles lockfile entries into accessor functions with typed slot parameters. The generated
//! code has no external runtime imports.

use crate::lockfile::LingoLock;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CodegenTarget {
    TypeScript,
    Rust,
}

pub struct CodegenOptions {
    pub target: CodegenTarget,
    pub source_locale: String,
    pub target_locales: Vec<String>,
}

/// Generates type-safe accessor code for all catalog items.
pub fn generate_code(lock: &LingoLock, options: &CodegenOptions) -> String {
    match options.target {
        CodegenTarget::TypeScript => generate_typescript(lock, options),
        CodegenTarget::Rust => generate_rust(lock, options),
    }
}

fn extract_slot_names(text: &str) -> Vec<String> {
    let mut slots = Vec::new();
    let mut i = 0;
    let chars: Vec<char> = text.chars().collect();
    while i < chars.len() {
        if chars[i] == '{' {
            i += 1;
            let start = i;
            while i < chars.len() && chars[i] != '}' && chars[i] != ',' {
                i += 1;
            }
            if i < chars.len() && (chars[i] == '}' || chars[i] == ',') {
                let slot: String = chars[start..i].iter().collect();
                let clean = slot.trim();
                if !clean.is_empty() && clean.chars().all(|c| c.is_alphanumeric() || c == '_' || c == '.') {
                    slots.push(clean.to_string());
                }
            }
        }
        i += 1;
    }
    slots.sort();
    slots.dedup();
    slots
}

fn generate_typescript(lock: &LingoLock, options: &CodegenOptions) -> String {
    let mut out = String::new();
    out.push_str("// Code generated by Glossa . DO NOT EDIT.\n");
    out.push_str("// Typed message accessors with no external runtime imports.\n\n");

    // 1. Generate Locale type
    let mut all_locales = vec![options.source_locale.clone()];
    for loc in &options.target_locales {
        if !all_locales.contains(loc) {
            all_locales.push(loc.clone());
        }
    }
    let union_types: Vec<String> = all_locales.iter().map(|l| format!("\"{l}\"")).collect();
    out.push_str(&format!("export type Locale = {};\n", union_types.join(" | ")));
    out.push_str(&format!("export const defaultLocale: Locale = \"{}\";\n\n", options.source_locale));

    // 2. Generate message functions
    out.push_str("export const m = {\n");

    for (_, entry) in &lock.entries {
        let fn_name = to_camel_case(&entry.canonical_text);
        if fn_name.is_empty() {
            continue;
        }

        let slots = extract_slot_names(&entry.canonical_text);

        if slots.is_empty() {
            // No slots, simple string getter
            out.push_str(&format!("  /**\n   * \"{}\"\n   */\n", entry.canonical_text.replace('\n', " ")));
            out.push_str(&format!("  {fn_name}: (locale: Locale = defaultLocale): string => {{\n"));
            out.push_str("    switch (locale) {\n");
            for (loc, loc_entry) in &entry.locales {
                let escaped = escape_ts_string(&loc_entry.translated_text);
                out.push_str(&format!("      case \"{loc}\": return \"{escaped}\";\n"));
            }
            let def_escaped = escape_ts_string(&entry.canonical_text);
            out.push_str(&format!("      default: return \"{def_escaped}\";\n"));
            out.push_str("    }\n");
            out.push_str("  },\n\n");
        } else {
            // Has slots, parameterized function
            let param_types: Vec<String> = slots.iter().map(|s| format!("{s}: string | number")).collect();
            out.push_str(&format!("  /**\n   * \"{}\"\n   */\n", entry.canonical_text.replace('\n', " ")));
            out.push_str(&format!(
                "  {fn_name}: (params: {{ {} }}, locale: Locale = defaultLocale): string => {{\n",
                param_types.join(", ")
            ));
            out.push_str("    let template = \"\";\n");
            out.push_str("    switch (locale) {\n");
            for (loc, loc_entry) in &entry.locales {
                let escaped = escape_ts_string(&loc_entry.translated_text);
                out.push_str(&format!("      case \"{loc}\": template = \"{escaped}\"; break;\n"));
            }
            let def_escaped = escape_ts_string(&entry.canonical_text);
            out.push_str(&format!("      default: template = \"{def_escaped}\"; break;\n"));
            out.push_str("    }\n");

            // Slot interpolation replacements
            for slot in &slots {
                out.push_str(&format!("    template = template.replaceAll(\"{{{slot}}}\", String(params.{slot}));\n"));
            }
            out.push_str("    return template;\n");
            out.push_str("  },\n\n");
        }
    }

    out.push_str("};\n");
    out
}

fn generate_rust(lock: &LingoLock, options: &CodegenOptions) -> String {
    let mut out = String::new();
    out.push_str("// Code generated by Glossa. DO NOT EDIT.\n\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    out.push_str("pub enum Locale {\n");
    out.push_str(&format!("    {},\n", to_pascal_case(&options.source_locale)));
    for loc in &options.target_locales {
        out.push_str(&format!("    {},\n", to_pascal_case(loc)));
    }
    out.push_str("}\n\n");

    out.push_str("pub mod m {\n");
    out.push_str("    use super::Locale;\n\n");

    for (_, entry) in &lock.entries {
        let fn_name = to_snake_case(&entry.canonical_text);
        if fn_name.is_empty() {
            continue;
        }

        let slots = extract_slot_names(&entry.canonical_text);
        if slots.is_empty() {
            out.push_str(&format!("    pub fn {fn_name}(locale: Locale) -> &'static str {{\n"));
            out.push_str("        match locale {\n");
            for (loc, loc_entry) in &entry.locales {
                let p = to_pascal_case(loc);
                let escaped = escape_ts_string(&loc_entry.translated_text);
                out.push_str(&format!("            Locale::{p} => \"{escaped}\",\n"));
            }
            let def_p = to_pascal_case(&options.source_locale);
            let def_escaped = escape_ts_string(&entry.canonical_text);
            out.push_str(&format!("            Locale::{def_p} => \"{def_escaped}\",\n"));
            out.push_str("        }\n");
            out.push_str("    }\n\n");
        } else {
            let params: Vec<String> = slots.iter().map(|s| format!("{s}: &str")).collect();
            out.push_str(&format!("    pub fn {fn_name}({}, locale: Locale) -> String {{\n", params.join(", ")));
            out.push_str("        let template = match locale {\n");
            for (loc, loc_entry) in &entry.locales {
                let p = to_pascal_case(loc);
                let escaped = escape_ts_string(&loc_entry.translated_text);
                out.push_str(&format!("            Locale::{p} => \"{escaped}\",\n"));
            }
            let def_p = to_pascal_case(&options.source_locale);
            let def_escaped = escape_ts_string(&entry.canonical_text);
            out.push_str(&format!("            Locale::{def_p} => \"{def_escaped}\",\n"));
            out.push_str("        };\n");
            out.push_str("        let mut res = template.to_string();\n");
            for slot in &slots {
                out.push_str(&format!("        res = res.replace(\"{{{slot}}}\", {slot});\n"));
            }
            out.push_str("        res\n");
            out.push_str("    }\n\n");
        }
    }

    out.push_str("}\n");
    out
}

fn to_camel_case(s: &str) -> String {
    let words: Vec<&str> = s.split(|c: char| !c.is_alphanumeric()).filter(|w| !w.is_empty()).collect();
    if words.is_empty() {
        return "msg".to_string();
    }
    let mut out = String::new();
    for (i, word) in words.iter().take(6).enumerate() {
        if i == 0 {
            out.push_str(&word.to_lowercase());
        } else {
            let mut chars = word.chars();
            if let Some(first) = chars.next() {
                out.push_str(&first.to_uppercase().to_string());
                out.push_str(&chars.as_str().to_lowercase());
            }
        }
    }
    if out.chars().next().map_or(false, |c| c.is_numeric()) {
        format!("msg{out}")
    } else {
        out
    }
}

fn to_snake_case(s: &str) -> String {
    let words: Vec<&str> = s.split(|c: char| !c.is_alphanumeric()).filter(|w| !w.is_empty()).collect();
    if words.is_empty() {
        return "msg".to_string();
    }
    let joined = words.iter().take(6).map(|w| w.to_lowercase()).collect::<Vec<_>>().join("_");
    if joined.chars().next().map_or(false, |c| c.is_numeric()) {
        format!("msg_{joined}")
    } else {
        joined
    }
}

fn to_pascal_case(s: &str) -> String {
    let clean: String = s.chars().filter(|c| c.is_alphanumeric()).collect();
    let mut chars = clean.chars();
    if let Some(first) = chars.next() {
        format!("{}{}", first.to_uppercase(), chars.as_str())
    } else {
        "Locale".to_string()
    }
}

fn escape_ts_string(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::coord::ApeironCoord;
    use crate::lockfile::{LockEntry, LocaleEntry};
    use std::collections::BTreeMap;

    #[test]
    fn test_codegen_typescript() {
        let mut lock = LingoLock::default();
        let mut entry = LockEntry {
            coord: ApeironCoord::from_str_canonical("Hello, {name}!"),
            source_hash: 0,
            canonical_text: "Hello, {name}!".to_string(),
            context: None,
            locales: BTreeMap::new(),
        };
        entry.locales.insert(
            "es".to_string(),
            LocaleEntry {
                translated_text: "¡Hola, {name}!".to_string(),
                translated_hash: 0,
                provider: "offline".to_string(),
                updated_at: "2026-01-01T00:00:00Z".to_string(),
                quality_score: 1.0,
            },
        );
        lock.entries.insert(entry.coord, entry);

        let opts = CodegenOptions {
            target: CodegenTarget::TypeScript,
            source_locale: "en".to_string(),
            target_locales: vec!["es".to_string()],
        };

        let ts = generate_code(&lock, &opts);
        assert!(ts.contains("export type Locale = \"en\" | \"es\";"));
        assert!(ts.contains("helloName: (params: { name: string | number }, locale: Locale = defaultLocale): string =>"));
        assert!(ts.contains("case \"es\": template = \"¡Hola, {name}!\"; break;"));
    }
}
